// getSize.js 基准尺寸唯一来源（总表见 aiDocs/样式设计指南.md「0. 基准尺寸表」）
// 公式：getSize(k) = (2 × 2k) / 10，即 0.4k，k 取任意数
// 返回纯数字（rem 单位下的数值），使用时在调用处拼单位，如 "#{getSize(8)}rem"
// 内部以 0.2rem 为最小单位，整数 k 恒输出 0.4 的倍数（对齐业界 4px 生态）
// 纪律：行内 style 禁止裸数值字面量，数值必出自 getSize(k)；一档一用途；改值只改指南总表，不改调用处
// 推荐档与全部尺寸数值：只参考 aiDocs/样式设计指南.md「0. 基准尺寸表」（单一来源，此处不重复列数字）

export default (k) => (2 * 2 * k) / 10
